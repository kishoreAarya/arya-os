import React, { useState, useEffect, useCallback, useMemo } from 'react';
import {
  ControlPlaneSnapshot,
  SystemHealthSummary,
  MissionSummary,
  OperationSummary,
  ApprovalSummary,
  RecoverySummary,
  CausalTraceSummary,
} from '../../types/controlPlane';
import {
  controlPlaneSnapshotService,
  MissionResourceSummary,
} from '../../services/controlPlaneSnapshotService';
import { SystemHealthPanel } from './SystemHealthPanel';
import { MissionOperationsPanel } from './MissionOperationsPanel';
import { OperationTimelinePanel } from './OperationTimelinePanel';
import { ApprovalCenterPanel } from './ApprovalCenterPanel';
import { RecoveryOperationsPanel } from './RecoveryOperationsPanel';
import { CausalEvidencePanel } from './CausalEvidencePanel';
import { ResourceStatusPanel } from './ResourceStatusPanel';
import { OperatorHUDErrorBoundary } from './OperatorHUDErrorBoundary';
export { OperatorHUDErrorBoundary } from './OperatorHUDErrorBoundary';
import {
  EpistemicBadge,
  LifecycleBadge,
  formatTimestamp,
} from './EpistemicIndicators';

export type OperatorHudTab =
  | 'overview'
  | 'health'
  | 'missions'
  | 'operations'
  | 'approvals'
  | 'recovery'
  | 'causal'
  | 'resources';

export interface OperatorHUDProps {
  /** Initial or pre-computed snapshot for controlled rendering */
  initialSnapshot?: ControlPlaneSnapshot | null;
  /** Initial active tab */
  defaultTab?: OperatorHudTab;
  /** Active visibility */
  isOpen?: boolean;
  /** Optional close callback (DOM presentation only) */
  onClose?: () => void;
  /** Custom wrapper CSS class */
  className?: string;
}

export const OperatorHUD: React.FC<OperatorHUDProps> = ({
  initialSnapshot,
  defaultTab = 'overview',
  isOpen = true,
  onClose,
  className = '',
}) => {
  const [snapshot, setSnapshot] = useState<ControlPlaneSnapshot | null>(null);
  const [activeTab, setActiveTab] = useState<OperatorHudTab>(defaultTab);
  const [selectedMissionId, setSelectedMissionId] = useState<string | null>(null);
  const [selectedOperationId, setSelectedOperationId] = useState<string | null>(null);
  const [errorState, setErrorState] = useState<string | null>(null);
  const [isRefreshing, setIsRefreshing] = useState(false);

  // Load snapshot safely
  const refreshSnapshot = useCallback(() => {
    try {
      setIsRefreshing(true);
      setErrorState(null);
      const snap = controlPlaneSnapshotService.getSnapshot();
      setSnapshot(snap);
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      setErrorState(msg);
    } finally {
      setIsRefreshing(false);
    }
  }, []);

  // Initialize snapshot on mount or when initialSnapshot changes
  useEffect(() => {
    if (initialSnapshot !== undefined) {
      setSnapshot(initialSnapshot);
    } else {
      refreshSnapshot();
    }
  }, [initialSnapshot, refreshSnapshot]);

  // Aggregate resources from selected mission or all missions
  const aggregatedResources = useMemo<readonly MissionResourceSummary[]>(() => {
    if (!snapshot) return [];
    if (selectedMissionId) {
      const detail = controlPlaneSnapshotService.projectMissionDetail(selectedMissionId);
      return detail?.resourceAllocations || [];
    }
    // Otherwise gather from the first mission with resources, or all missions
    const allResources: MissionResourceSummary[] = [];
    for (const m of snapshot.missions) {
      const detail = controlPlaneSnapshotService.projectMissionDetail(m.missionId);
      if (detail && detail.resourceAllocations.length > 0) {
        allResources.push(...detail.resourceAllocations);
      }
    }
    return Object.freeze(allResources);
  }, [snapshot, selectedMissionId]);

  if (!isOpen) return null;

  const tabs: Array<{ id: OperatorHudTab; label: string; count?: number }> = [
    { id: 'overview', label: 'OVERVIEW' },
    { id: 'health', label: 'HEALTH', count: snapshot?.systemHealth ? 9 : 0 },
    { id: 'missions', label: 'MISSIONS', count: snapshot?.missions.length ?? 0 },
    { id: 'operations', label: 'OPERATIONS', count: snapshot?.operations.length ?? 0 },
    { id: 'approvals', label: 'APPROVALS', count: snapshot?.approvals.length ?? 0 },
    { id: 'recovery', label: 'RECOVERY', count: snapshot?.recovery.length ?? 0 },
    { id: 'causal', label: 'CAUSAL TRACE', count: snapshot?.causalTraces.length ?? 0 },
    { id: 'resources', label: 'RESOURCES', count: aggregatedResources.length },
  ];

  return (
    <div
      data-testid="operator-hud"
      role="region"
      aria-label="AryaOS Control Plane Operator HUD"
      className={`fixed inset-2 md:inset-4 z-50 flex flex-col rounded-lg overflow-hidden font-mono shadow-2xl backdrop-blur-md ${className}`}
      style={{
        backgroundColor: 'rgba(4, 6, 10, 0.94)',
        border: '1px solid rgba(245, 158, 11, 0.35)',
        boxShadow: '0 20px 50px rgba(0, 0, 0, 0.9), 0 0 30px rgba(245, 158, 11, 0.1)',
        color: '#f8fafc',
      }}
    >
      {/* Top Header Bar */}
      <header
        data-testid="hud-header"
        className="flex items-center justify-between flex-wrap gap-3 px-4 py-3 border-b border-slate-800 bg-slate-950/80"
      >
        <div className="flex items-center gap-3">
          <div className="flex items-center gap-2">
            <span className="w-2.5 h-2.5 rounded-full bg-amber-500 animate-pulse shadow-sm shadow-amber-500/50" />
            <h1 className="text-sm font-bold tracking-widest text-slate-100 uppercase">
              ARYAOS V1 // CONTROL PLANE OPERATOR HUD
            </h1>
          </div>
          <span className="text-[0.625rem] px-1.5 py-0.5 rounded bg-slate-800 text-slate-400 border border-slate-700">
            STAGE 24 PROJECTION
          </span>
        </div>

        {/* Telemetry metadata & refresh */}
        <div className="flex items-center gap-3 flex-wrap text-xs">
          {snapshot && (
            <>
              <div className="flex items-center gap-1.5 text-[0.6875rem] text-slate-400">
                <span>SNAPSHOT:</span>
                <strong data-testid="hud-snapshot-id" className="text-amber-400">
                  {snapshot.snapshotId}
                </strong>
              </div>
              <div className="flex items-center gap-1.5 text-[0.6875rem] text-slate-400">
                <span>TIME:</span>
                <span data-testid="hud-timestamp" className="text-slate-200">
                  {formatTimestamp(snapshot.generatedAt)}
                </span>
              </div>
              {snapshot.systemHealth && (
                <div className="flex items-center gap-1.5">
                  <span className="text-[0.6875rem] text-slate-400">HEALTH:</span>
                  <LifecycleBadge state={snapshot.systemHealth.overallStatus} />
                </div>
              )}
            </>
          )}

          {/* Observational Local Refresh Button (Zero Consequential Action) */}
          <button
            type="button"
            data-testid="hud-refresh-btn"
            onClick={refreshSnapshot}
            disabled={isRefreshing}
            className="flex items-center gap-1 px-2.5 py-1 text-[0.6875rem] font-bold rounded bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 transition-colors"
            title="Re-read current authoritative projection snapshot"
          >
            <span>{isRefreshing ? 'REFRESHING...' : 'REFRESH SNAPSHOT'}</span>
          </button>

          {/* Close button if provided */}
          {onClose && (
            <button
              type="button"
              data-testid="hud-close-btn"
              onClick={onClose}
              className="px-2 py-1 text-xs font-bold rounded bg-slate-900 hover:bg-slate-800 text-slate-400 hover:text-slate-200 border border-slate-800"
              title="Close Operator HUD"
            >
              ESC / CLOSE
            </button>
          )}
        </div>
      </header>

      {/* Navigation Tabs */}
      <nav
        data-testid="hud-tab-bar"
        aria-label="HUD Sections"
        className="flex items-center gap-1 px-4 py-2 border-b border-slate-800/80 bg-slate-950/40 overflow-x-auto"
      >
        {tabs.map((tab) => {
          const isActive = activeTab === tab.id;
          return (
            <button
              key={tab.id}
              type="button"
              role="tab"
              aria-selected={isActive}
              data-testid={`hud-tab-${tab.id}`}
              onClick={() => setActiveTab(tab.id)}
              className={`flex items-center gap-1.5 px-3 py-1 text-xs rounded transition-all whitespace-nowrap ${
                isActive
                  ? 'bg-amber-500/15 text-amber-300 font-bold border border-amber-500/40 shadow-sm'
                  : 'text-slate-400 hover:text-slate-200 hover:bg-slate-900/60 border border-transparent'
              }`}
            >
              <span>{tab.label}</span>
              {tab.count !== undefined && tab.count > 0 && (
                <span
                  className={`text-[0.5625rem] px-1 rounded ${
                    isActive ? 'bg-amber-500/30 text-amber-200' : 'bg-slate-800 text-slate-400'
                  }`}
                >
                  {tab.count}
                </span>
              )}
            </button>
          );
        })}
      </nav>

      {/* Main Panel Content Area */}
      <main
        data-testid="hud-content-area"
        className="flex-1 overflow-y-auto p-4 flex flex-col gap-4"
      >
        {errorState ? (
          <div
            data-testid="hud-error-boundary"
            className="p-6 rounded border border-rose-800 bg-rose-950/30 text-rose-300 flex flex-col gap-2"
          >
            <div className="flex items-center gap-2 font-bold text-sm">
              <span className="text-rose-400">ERROR:</span>
              <span>CONTROL PLANE SNAPSHOT PROJECTION FAILED</span>
            </div>
            <p className="text-xs text-rose-200/80">{errorState}</p>
            <button
              type="button"
              data-testid="hud-error-retry-btn"
              onClick={refreshSnapshot}
              className="mt-2 w-max px-3 py-1 text-xs font-semibold rounded bg-rose-900/40 hover:bg-rose-900/60 border border-rose-700 text-rose-100"
            >
              RETRY OBSERVATIONAL READ
            </button>
          </div>
        ) : !snapshot ? (
          <div
            data-testid="hud-loading-state"
            className="p-8 text-center text-slate-400 text-xs flex flex-col items-center justify-center h-full gap-2"
          >
            <span className="animate-spin text-amber-500 text-lg">&bull;</span>
            <span>READING AUTHORITATIVE CONTROL PLANE PROJECTIONS...</span>
          </div>
        ) : (
          <>
            {/* OVERVIEW TAB: Displays a consolidated summary across all subsystems */}
            {activeTab === 'overview' && (
              <div data-testid="hud-overview-section" className="flex flex-col gap-4">
                <OperatorHUDErrorBoundary panelTitle="System Health Subsystem">
                  <SystemHealthPanel health={snapshot.systemHealth} />
                </OperatorHUDErrorBoundary>
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  <OperatorHUDErrorBoundary panelTitle="Approval Center">
                    <ApprovalCenterPanel approvals={snapshot.approvals} />
                  </OperatorHUDErrorBoundary>
                  <OperatorHUDErrorBoundary panelTitle="Recovery Operations">
                    <RecoveryOperationsPanel recovery={snapshot.recovery} />
                  </OperatorHUDErrorBoundary>
                </div>
                <OperatorHUDErrorBoundary panelTitle="Mission Operations">
                  <MissionOperationsPanel
                    missions={snapshot.missions}
                    selectedMissionId={selectedMissionId}
                    onSelectMission={setSelectedMissionId}
                  />
                </OperatorHUDErrorBoundary>
              </div>
            )}

            {/* HEALTH TAB */}
            {activeTab === 'health' && (
              <OperatorHUDErrorBoundary panelTitle="System Health Subsystem">
                <SystemHealthPanel health={snapshot.systemHealth} />
              </OperatorHUDErrorBoundary>
            )}

            {/* MISSIONS TAB */}
            {activeTab === 'missions' && (
              <OperatorHUDErrorBoundary panelTitle="Mission Operations">
                <MissionOperationsPanel
                  missions={snapshot.missions}
                  selectedMissionId={selectedMissionId}
                  onSelectMission={setSelectedMissionId}
                />
              </OperatorHUDErrorBoundary>
            )}

            {/* OPERATIONS TAB */}
            {activeTab === 'operations' && (
              <OperatorHUDErrorBoundary panelTitle="Operation Timeline">
                <OperationTimelinePanel
                  operations={snapshot.operations}
                  selectedOperationId={selectedOperationId}
                  onSelectOperation={setSelectedOperationId}
                />
              </OperatorHUDErrorBoundary>
            )}

            {/* APPROVALS TAB */}
            {activeTab === 'approvals' && (
              <OperatorHUDErrorBoundary panelTitle="Approval Center">
                <ApprovalCenterPanel approvals={snapshot.approvals} />
              </OperatorHUDErrorBoundary>
            )}

            {/* RECOVERY TAB */}
            {activeTab === 'recovery' && (
              <OperatorHUDErrorBoundary panelTitle="Recovery Operations">
                <RecoveryOperationsPanel recovery={snapshot.recovery} />
              </OperatorHUDErrorBoundary>
            )}

            {/* CAUSAL TRACE TAB */}
            {activeTab === 'causal' && (
              <OperatorHUDErrorBoundary panelTitle="Causal Evidence">
                <CausalEvidencePanel traces={snapshot.causalTraces} />
              </OperatorHUDErrorBoundary>
            )}

            {/* RESOURCES TAB */}
            {activeTab === 'resources' && (
              <OperatorHUDErrorBoundary panelTitle="Resource Status">
                <ResourceStatusPanel
                  resources={aggregatedResources}
                  missionTitle={
                    selectedMissionId
                      ? snapshot.missions.find((m) => m.missionId === selectedMissionId)?.title
                      : undefined
                  }
                />
              </OperatorHUDErrorBoundary>
            )}
          </>
        )}
      </main>

      {/* Epistemic Legend Footer */}
      <footer
        data-testid="hud-footer"
        className="flex items-center justify-between flex-wrap gap-2 px-4 py-2 border-t border-slate-800 bg-slate-950/80 text-[0.625rem] text-slate-500"
      >
        <div className="flex items-center gap-2 flex-wrap">
          <span className="font-bold text-slate-400">EPISTEMIC STANDARDS:</span>
          <div className="flex items-center gap-1.5">
            <EpistemicBadge status="OBSERVED" size="sm" />
            <EpistemicBadge status="CONFIRMED" size="sm" />
            <EpistemicBadge status="INFERRED" size="sm" />
            <EpistemicBadge status="PROJECTED" size="sm" />
            <EpistemicBadge status="UNKNOWN" size="sm" />
          </div>
        </div>

        <div className="flex items-center gap-3">
          <span>* Observational Facade Only. No Consequential Authority.</span>
          <span className="text-slate-400 font-bold">STAGE 24 V1</span>
        </div>
      </footer>
    </div>
  );
};
